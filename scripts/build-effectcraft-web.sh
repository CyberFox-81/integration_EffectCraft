# Build EffectCraft for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-effectcraft-web.sh [EFFECTCRAFT_CHECKOUT]
#
#   EFFECTCRAFT_CHECKOUT  an existing clone of github.com/storytold/effectcraft. Without it the
#                       script clones EFFECTCRAFT_REF into build/effectcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in EffectCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   EFFECTCRAFT_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
#   CRAFT_FONTS_DIR  a clone of storytold/craft-fonts, to embed the shared Japanese fonts
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
EFFECTCRAFT_REF="${EFFECTCRAFT_REF:-4b58cd2eb733bdc7ad39161e93dd8e2ff4af6416}"
SRC="${1:-$APP_DIR/build/effectcraft}"
PATCH="$APP_DIR/patches/effectcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/effectcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$EFFECTCRAFT_REF"
fi

if grep -rq 'effectcraft:ready' "$SRC/apps/effectcraft-web/src"; then
	echo "bridge patch already applied"
else
	git -C "$SRC" apply "$PATCH"
fi

cargo_args=(build --profile release -p effectcraft-web --target wasm32-unknown-unknown --features unbranded)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/effectcraft_web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
OUT_NAME=effectcraft_web
wasm-bindgen --target web --no-typescript --out-dir "$STAGE" --out-name "$OUT_NAME" "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -O2 --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/${OUT_NAME}_bg.wasm" -o "$STAGE/${OUT_NAME}_bg.opt.wasm"
	mv "$STAGE/${OUT_NAME}_bg.opt.wasm" "$STAGE/${OUT_NAME}_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

mkdir -p "$OUT"
hash() { sha256sum "$1" | cut -c1-16; }
# One folder per build (its name in build.txt): the files keep the names the app's own code uses
# for them, and a new version is a new folder, so browsers never mix cached files of two builds.
BUILD="build-$(cat "$STAGE/$OUT_NAME.js" "$STAGE/${OUT_NAME}_bg.wasm" | sha256sum | cut -c1-12)"
rm -rf "$OUT"/build-*
DEST="$OUT/$BUILD"
mkdir -p "$DEST"
JS_NAME="$OUT_NAME.js"
WASM_NAME="${OUT_NAME}_bg.wasm"
cp "$STAGE/$OUT_NAME.js" "$DEST/$JS_NAME"
cp "$STAGE/${OUT_NAME}_bg.wasm" "$DEST/$WASM_NAME"
# JavaScript the Rust code brings along (`#[wasm_bindgen(module = …)]`), imported by the glue.
rm -rf "$DEST/snippets"
if [ -d "$STAGE/snippets" ]; then cp -R "$STAGE/snippets" "$DEST/snippets"; fi
# The render workers and the audio worklet EffectCraft starts by relative URLs.
cp "$SRC/apps/effectcraft-web/web/worker.js" "$DEST/worker.js"
cp "$SRC/apps/effectcraft-web/web/audio-worklet.js" "$DEST/audio-worklet.js"

# EffectCraft's licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md ASSETS.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/EFFECTCRAFT-$f"; fi
done

cat > "$DEST/boot.js" <<BOOT
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts EffectCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-effectcraft-web.sh from EffectCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('EffectCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'effectcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	// Compile once: the page and its render workers instantiate the same module.
	const wasmUrl = new URL('./$WASM_NAME', import.meta.url)
	let module
	try {
		module = await WebAssembly.compileStreaming(fetch(wasmUrl))
	} catch {
		module = await WebAssembly.compile(await (await fetch(wasmUrl)).arrayBuffer())
	}
	window.effectcraftModule = module
	const app = await import('./$JS_NAME')
	await app.default({ module_or_path: module })
	await app.start('effectcraft_canvas')
} catch (error) {
	reportFailure(error)
}
BOOT

# The page in the editor's iframe: static, so relative URLs (workers, worklets) resolve in its
# build folder.
cat > "$DEST/frame.html" <<FRAME
<!DOCTYPE html>
<!-- Generated by scripts/build-effectcraft-web.sh. SPDX-License-Identifier: AGPL-3.0-or-later -->
<html lang="en">
<head>
	<meta charset="utf-8">
	<meta name="viewport" content="width=device-width, initial-scale=1, user-scalable=no">
	<meta name="robots" content="noindex, nofollow">
	<title>EffectCraft</title>
	<style>
		html, body { margin: 0; padding: 0; width: 100%; height: 100%; overflow: hidden; background: #1b1c1f; }
		#effectcraft_canvas { position: absolute; inset: 0; width: 100%; height: 100%; display: block; }
		#loading { position: absolute; inset: 0; display: flex; align-items: center; justify-content: center; pointer-events: none; }
	</style>
</head>
<body>
	<canvas id="effectcraft_canvas"></canvas>
	<div id="loading"></div>
	<script type="module" src="boot.js"></script>
</body>
</html>
FRAME
echo "$BUILD" > "$OUT/build.txt"

echo "EffectCraft web build:"
ls -lh "$OUT"
